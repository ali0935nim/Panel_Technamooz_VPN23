async def login_rate_limited(ip: str) -> bool:
    now = time.time()
    async with LOGIN_LOCK:
        attempts = [t for t in LOGIN_FAILURES.get(ip, []) if now - t < LOGIN_WINDOW]
        LOGIN_FAILURES[ip] = attempts
        return len(attempts) >= LOGIN_MAX_FAILURES

